<section class="card" id="about">
    <h2><span class="num">1</span>About this policy</h2>
    <p>This policy explains what personal data the Fitness Tracker app (on iPhone, Android and desktop) and its server collect, why, and what control you have over it. "We" and "us" mean the team that develops and runs Fitness Tracker.</p>
    <p>By creating an account you confirm you have read this policy. If you do not agree with it, please do not use the app.</p>
</section>

<section class="card" id="collect">
    <h2><span class="num">2</span>What we collect</h2>
    <p>We only collect what the app needs to work. Most of it is information you enter yourself.</p>
    <table class="table">
        <tr>
            <th>Account</th>
            <td>Your name, email address and password. The password is stored only as a one-way hash, so nobody, including us, can read it.</td>
        </tr>
        <tr>
            <th>Profile and body measurements</th>
            <td>Date of birth (to work out your age), gender, height, weight, activity level and fitness goal (lose weight, build muscle or maintain). We use these to work out your calorie and macro targets.</td>
        </tr>
        <tr>
            <th>Health and fitness logs</th>
            <td>The meals and foods you log, custom foods you add, your favourite foods, your weight history, the workouts and activities you log (with duration and calories burned), and the workouts, schedules and weekly plans you create.</td>
        </tr>
        <tr>
            <th>Achievements and streaks</th>
            <td>The badges you unlock and your activity streaks.</td>
        </tr>
        <tr>
            <th>Notifications</th>
            <td>A push notification token for your device, your time zone, your notification settings, a record of the reminders we sent you and whether you opened them, when you last used the app, and the time of day you usually use it, so reminders arrive at a helpful time.</td>
        </tr>
        <tr>
            <th>Technical data</th>
            <td>Your IP address and basic request information, used to block repeated sign-in attempts and to keep the service secure. Your app language is sent with each request so we can reply in that language.</td>
        </tr>
    </table>
    <p class="muted" style="margin-top: 12px;">We do not collect your precise location, contacts, photos or data from Apple Health or Google Fit.</p>
</section>

<section class="card" id="device">
    <h2><span class="num">3</span>What stays on your phone</h2>
    <p>Some things never leave your device and are never sent to us:</p>
    <ul>
        <li>Your profile picture, if you choose one.</li>
        <li>Your theme and language preferences.</li>
        <li>Workout programs you export to a file, unless you choose to share that file yourself.</li>
        <li>Your sign-in token, which is kept in your device's secure storage (Keychain on iPhone, Keystore on Android).</li>
    </ul>
    <p>When you scan a food barcode, the app looks up the barcode number with Open Food Facts (see section 6). Your camera images are not stored or uploaded.</p>
</section>

<section class="card" id="use">
    <h2><span class="num">4</span>How we use your data</h2>
    <ul>
        <li>To create and secure your account, sign you in and let you reset a forgotten password.</li>
        <li>To show your daily calories, macros, workouts, progress charts and achievements.</li>
        <li>To suggest workouts based on your goal and history. These suggestions are calculated on our server; your data is not sent to any outside AI service.</li>
        <li>To send the reminders and achievement notifications you have turned on.</li>
        <li>To fix problems, prevent abuse and keep the service running.</li>
    </ul>
    <p>Where the EU or UK GDPR applies, we rely on our contract with you (providing the app you signed up for) for the data the app needs to work, on your explicit consent for health and fitness data, which you give by entering it, and on our legitimate interest in keeping the service secure. You can withdraw consent at any time by deleting the data or your account.</p>
</section>

<section class="card" id="never">
    <h2><span class="num">5</span>What we never do</h2>
    <div class="badges">
        <span class="badge">No selling of data</span>
        <span class="badge">No health data in ads</span>
        <span class="badge">No data brokers</span>
    </div>
    <ul>
        <li>We do not sell, rent or trade your personal data.</li>
        <li>We do not use your health and fitness data for advertising or marketing, and we do not share it with advertisers, ad networks or data brokers. Ads are never chosen based on what you eat, weigh or log.</li>
    </ul>
</section>

<section class="card" id="share">
    <h2><span class="num">6</span>Who we share it with</h2>
    <p>We share data only with the services below, and only what each one needs to do its job for us:</p>
    <h3>Google Firebase Cloud Messaging</h3>
    <p>Delivers push notifications. It receives your device's push token and the text of each notification. See <a href="https://firebase.google.com/support/privacy" rel="noopener">Firebase's privacy information</a>.</p>
    <h3>Google AdMob (Android app only)</h3>
    <p>The Android app shows banner ads from Google AdMob, which helps pay for the app. To choose, show and measure ads, Google's ad SDK collects information from your device directly, such as its advertising ID, IP address, device model and how you interact with the ads. Google may use this to show you personalised ads. We do not send AdMob anything about your account, body measurements or logs. See <a href="https://policies.google.com/technologies/partner-sites" rel="noopener">how Google uses data from apps that use its services</a>.</p>
    <p>You can reset your advertising ID or turn off ad personalisation in your phone's settings (<em>Settings → Google → Ads</em> or <em>Settings → Privacy → Ads</em>, depending on your phone). The iPhone app currently shows no ads; if that changes, it will ask your permission before any tracking.</p>
    <h3>Our email provider</h3>
    <p>Sends password reset codes. It receives your email address and the code.</p>
    <h3>Open Food Facts</h3>
    <p>When you scan a barcode, the app sends the barcode number directly to the <a href="https://world.openfoodfacts.org/privacy" rel="noopener">Open Food Facts</a> database to find the product. No account details are sent with it.</p>
    <h3>When the law requires it</h3>
    <p>We may disclose data if we are legally required to, for example by a court order, or to protect the safety of our users.</p>
    <p>If these services process data outside your country, they do so under their own safeguards, such as the European Commission's standard contractual clauses.</p>
</section>

<section class="card" id="security">
    <h2><span class="num">7</span>Storage and security</h2>
    <p>Your account data is stored on a server we operate. We protect it by encrypting traffic between the app and the server (HTTPS), storing passwords only as hashes, limiting repeated sign-in and reset attempts, and restricting who can access the server. No system is perfectly secure, but we work to protect your data and will tell you if a breach affects you, as the law requires.</p>
</section>

<section class="card" id="retention">
    <h2><span class="num">8</span>How long we keep it</h2>
    <ul>
        <li>Your account and logs are kept for as long as you have an account.</li>
        <li>When you delete your account, your profile, logs, workouts, achievements, device tokens and notification history are permanently deleted straight away. Server backups, if any, are overwritten in the normal course of operation.</li>
        <li>Password reset codes expire after 30 minutes and are deleted once used. Sign-in attempt counters expire within an hour.</li>
    </ul>
</section>

<section class="card" id="rights">
    <h2><span class="num">9</span>Your rights and choices</h2>
    <ul>
        <li><strong>See and correct your data:</strong> your profile, logs and workouts are all visible and editable in the app.</li>
        <li><strong>Delete your account:</strong> in the app, open <em>Me → Settings → Delete Account</em>. This permanently removes your account and all of its data.</li>
        <li><strong>Ads:</strong> turn off ad personalisation or reset your advertising ID in your phone's settings (see section 6).</li>
        <li><strong>Notifications:</strong> choose which reminders you get in <em>Me → Settings</em>, or turn them all off in your phone's settings.</li>
        <li><strong>Other requests:</strong> depending on where you live (for example under the GDPR, Moroccan law 09-08 or California law), you may also have the right to get a copy of your data, restrict or object to its use, or withdraw consent. Contact us to make a request; we will reply within one month.</li>
    </ul>
    <p>If you believe we have not handled your data properly, you can complain to your local data protection authority (for example the CNIL in France or the CNDP in Morocco).</p>
</section>

<section class="card" id="children">
    <h2><span class="num">10</span>Children</h2>
    <p>Fitness Tracker is not meant for children under 13, and we do not knowingly collect data from them. In countries where a higher age applies (up to 16 in parts of the EU), users below that age need a parent's permission. If you think a child has given us data, contact us and we will delete it.</p>
</section>

