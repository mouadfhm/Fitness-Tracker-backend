<section class="card" id="about">
    <h2><span class="num">1</span>À propos de cette politique</h2>
    <p>Cette politique explique quelles données personnelles l'application Fitness Tracker (sur iPhone, Android et ordinateur) et son serveur collectent, pourquoi, et comment vous gardez le contrôle. « Nous » désigne l'équipe qui développe et exploite Fitness Tracker.</p>
    <p>En créant un compte, vous confirmez avoir lu cette politique. Si vous n'êtes pas d'accord, merci de ne pas utiliser l'application.</p>
</section>

<section class="card" id="collect">
    <h2><span class="num">2</span>Ce que nous collectons</h2>
    <p>Nous ne collectons que ce dont l'application a besoin pour fonctionner. Il s'agit surtout d'informations que vous saisissez vous-même.</p>
    <table class="table">
        <tr>
            <th>Compte</th>
            <td>Votre nom, votre adresse e-mail et votre mot de passe. Le mot de passe n'est conservé que sous forme de hachage irréversible : personne, nous compris, ne peut le lire.</td>
        </tr>
        <tr>
            <th>Profil et mensurations</th>
            <td>Âge, sexe, taille, poids, niveau d'activité et objectif (perdre du poids, prendre du muscle ou maintenir). Nous les utilisons pour calculer vos objectifs de calories et de macronutriments.</td>
        </tr>
        <tr>
            <th>Journaux de santé et de sport</th>
            <td>Les repas et aliments que vous enregistrez, les aliments personnalisés que vous ajoutez, vos aliments favoris, l'historique de votre poids, les séances et activités que vous enregistrez (avec leur durée et les calories brûlées), ainsi que les séances, plannings et programmes hebdomadaires que vous créez.</td>
        </tr>
        <tr>
            <th>Succès et séries</th>
            <td>Les badges que vous débloquez et vos séries d'activité.</td>
        </tr>
        <tr>
            <th>Notifications</th>
            <td>Un identifiant de notification push pour votre appareil, votre fuseau horaire, vos réglages de notification, l'historique des rappels envoyés et si vous les avez ouverts, la date de votre dernière utilisation de l'application et le moment de la journée où vous l'utilisez habituellement, afin que les rappels arrivent au bon moment.</td>
        </tr>
        <tr>
            <th>Données techniques</th>
            <td>Votre adresse IP et des informations de base sur les requêtes, utilisées pour bloquer les tentatives de connexion répétées et sécuriser le service. La langue de l'application est envoyée avec chaque requête pour que nous répondions dans cette langue.</td>
        </tr>
    </table>
    <p class="muted" style="margin-top: 12px;">Nous ne collectons pas votre position précise, vos contacts, vos photos, votre identifiant publicitaire ni de données d'Apple Santé ou de Google Fit.</p>
</section>

<section class="card" id="device">
    <h2><span class="num">3</span>Ce qui reste sur votre téléphone</h2>
    <p>Certaines données ne quittent jamais votre appareil et ne nous sont jamais envoyées :</p>
    <ul>
        <li>Votre photo de profil, si vous en choisissez une.</li>
        <li>Vos préférences de thème et de langue.</li>
        <li>Les programmes d'entraînement que vous exportez dans un fichier, sauf si vous choisissez vous-même de partager ce fichier.</li>
        <li>Votre jeton de connexion, conservé dans le stockage sécurisé de votre appareil (Trousseau sur iPhone, Keystore sur Android).</li>
    </ul>
    <p>Lorsque vous scannez le code-barres d'un aliment, l'application recherche ce numéro dans Open Food Facts (voir la section 6). Les images de l'appareil photo ne sont ni enregistrées ni envoyées.</p>
</section>

<section class="card" id="use">
    <h2><span class="num">4</span>Comment nous utilisons vos données</h2>
    <ul>
        <li>Pour créer et sécuriser votre compte, vous connecter et vous permettre de réinitialiser un mot de passe oublié.</li>
        <li>Pour afficher vos calories et macronutriments du jour, vos séances, vos graphiques de progression et vos succès.</li>
        <li>Pour vous suggérer des séances selon votre objectif et votre historique. Ces suggestions sont calculées sur notre serveur ; vos données ne sont envoyées à aucun service d'IA extérieur.</li>
        <li>Pour envoyer les rappels et les notifications de succès que vous avez activés.</li>
        <li>Pour corriger les problèmes, prévenir les abus et assurer le fonctionnement du service.</li>
    </ul>
    <p>Lorsque le RGPD s'applique, nous nous fondons sur notre contrat avec vous (vous fournir l'application à laquelle vous vous êtes inscrit) pour les données nécessaires à son fonctionnement, sur votre consentement explicite pour les données de santé et de sport, que vous donnez en les saisissant, et sur notre intérêt légitime à sécuriser le service. Vous pouvez retirer votre consentement à tout moment en supprimant ces données ou votre compte.</p>
</section>

<section class="card" id="never">
    <h2><span class="num">5</span>Ce que nous ne faisons jamais</h2>
    <div class="badges">
        <span class="badge">Aucune vente de données</span>
        <span class="badge">Aucun pistage publicitaire</span>
        <span class="badge">Aucun courtier en données</span>
    </div>
    <ul>
        <li>Nous ne vendons, ne louons ni n'échangeons vos données personnelles.</li>
        <li>Nous n'utilisons pas vos données de santé et de sport à des fins publicitaires ou marketing, et nous ne les partageons ni avec des annonceurs ni avec des courtiers en données.</li>
        <li>Nous ne vous suivons pas sur les applications ou sites web d'autres entreprises.</li>
    </ul>
</section>

<section class="card" id="share">
    <h2><span class="num">6</span>Avec qui nous les partageons</h2>
    <p>Nous ne partageons des données qu'avec les services ci-dessous, et uniquement ce dont chacun a besoin pour fonctionner :</p>
    <h3>Google Firebase Cloud Messaging</h3>
    <p>Envoie les notifications push. Il reçoit l'identifiant push de votre appareil et le texte de chaque notification. Voir <a href="https://firebase.google.com/support/privacy" rel="noopener">les informations de confidentialité de Firebase</a>.</p>
    <h3>Notre prestataire d'e-mail</h3>
    <p>Envoie les codes de réinitialisation du mot de passe. Il reçoit votre adresse e-mail et le code.</p>
    <h3>Open Food Facts</h3>
    <p>Lorsque vous scannez un code-barres, l'application envoie directement ce numéro à la base <a href="https://world.openfoodfacts.org/privacy" rel="noopener">Open Food Facts</a> pour trouver le produit. Aucune information de compte n'est envoyée avec.</p>
    <h3>Lorsque la loi l'exige</h3>
    <p>Nous pouvons communiquer des données si la loi nous y oblige, par exemple sur décision de justice, ou pour protéger la sécurité de nos utilisateurs.</p>
    <p>Si ces services traitent des données hors de votre pays, ils le font avec leurs propres garanties, comme les clauses contractuelles types de la Commission européenne.</p>
</section>

<section class="card" id="security">
    <h2><span class="num">7</span>Stockage et sécurité</h2>
    <p>Les données de votre compte sont stockées sur un serveur que nous exploitons. Nous les protégeons en chiffrant les échanges entre l'application et le serveur (HTTPS), en ne conservant les mots de passe que sous forme hachée, en limitant les tentatives répétées de connexion et de réinitialisation, et en restreignant l'accès au serveur. Aucun système n'est parfaitement sûr, mais nous faisons le nécessaire pour protéger vos données et vous préviendrons si une violation vous concerne, comme la loi l'exige.</p>
</section>

<section class="card" id="retention">
    <h2><span class="num">8</span>Durée de conservation</h2>
    <ul>
        <li>Votre compte et vos journaux sont conservés tant que votre compte existe.</li>
        <li>Lorsque vous supprimez votre compte, votre profil, vos journaux, vos séances, vos succès, vos identifiants d'appareil et votre historique de notifications sont définitivement supprimés immédiatement. Les éventuelles sauvegardes du serveur sont écrasées au fil du fonctionnement normal.</li>
        <li>Les codes de réinitialisation expirent au bout de 30 minutes et sont supprimés une fois utilisés. Les compteurs de tentatives de connexion expirent en moins d'une heure.</li>
    </ul>
</section>

<section class="card" id="rights">
    <h2><span class="num">9</span>Vos droits et vos choix</h2>
    <ul>
        <li><strong>Consulter et corriger vos données :</strong> votre profil, vos journaux et vos séances sont tous visibles et modifiables dans l'application.</li>
        <li><strong>Supprimer votre compte :</strong> dans l'application, ouvrez <em>Moi → Paramètres → Supprimer le compte</em>. Votre compte et toutes ses données sont alors définitivement supprimés.</li>
        <li><strong>Notifications :</strong> choisissez les rappels que vous recevez dans <em>Moi → Paramètres</em>, ou désactivez-les tous dans les réglages de votre téléphone.</li>
        <li><strong>Autres demandes :</strong> selon votre lieu de résidence (par exemple au titre du RGPD, de la loi marocaine 09-08 ou du droit californien), vous pouvez aussi avoir le droit d'obtenir une copie de vos données, d'en limiter l'utilisation ou de vous y opposer, ou de retirer votre consentement. Contactez-nous pour toute demande ; nous répondrons sous un mois.</li>
    </ul>
    <p>Si vous estimez que nous n'avons pas traité vos données correctement, vous pouvez déposer une réclamation auprès de votre autorité de protection des données (par exemple la CNIL en France ou la CNDP au Maroc).</p>
</section>

<section class="card" id="children">
    <h2><span class="num">10</span>Enfants</h2>
    <p>Fitness Tracker n'est pas destiné aux enfants de moins de 13 ans, et nous ne collectons pas sciemment leurs données. Dans les pays où un âge plus élevé s'applique (jusqu'à 15 ans en France et 16 ans dans d'autres pays de l'UE), les utilisateurs plus jeunes ont besoin de l'autorisation d'un parent. Si vous pensez qu'un enfant nous a transmis des données, contactez-nous et nous les supprimerons.</p>
</section>

